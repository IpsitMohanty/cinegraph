"""CineGraph Explore evaluation harness.

Runs Explore over a fixed set of canonical seed films spanning eras and
countries, and dumps the seed + its top-N results + full explanations to a
judgeable markdown table (eval/explore_eval.md) with an empty `judgment`
column (interesting / trivial / wrong) and an `edge_integrity` column
(defaulted to "unverified").

`edge_integrity` is evaluation metadata only -- it never feeds scoring or
ranking. It exists so a genuinely useful result with a malformed/imprecise
explanation (Shakespeare-Wallah: Satyajit Ray shown as "writer" -- his role
on the seed, Pather Panchali -- when he actually composed Shakespeare-
Wallah's score; the explanation always shows the person's SEED-side role,
not their role on the specific candidate) isn't mislabeled `wrong` when the
underlying film-to-film relation is real. Valid values: valid, wrong_role,
overbroad_role, weak_credit, version_problem, unverified. Auto-detecting
which of these applies is NOT attempted here -- that's the deferred role-
normalization project; this harness only adds the column and defaults it.

This harness only produces the judgeable artifact -- it does not label it.
The labeling is a separate, human pass (see PREDICTIONS.md). Run this only
after PREDICTIONS.md is written and committed -- that ordering is the whole
point of pre-registration.

Seeds are resolved by (title, year) through cde.resolve.resolve_one_title(),
not hand-typed tconsts -- typing IMDb IDs from memory is exactly how a wrong
film silently ends up in the table (this bit during manual smoke-testing of
this same engine; see PREDICTIONS.md's disclosure note).

Usage: python eval_explore.py [--n 10] [--out eval/explore_eval.md]
"""

from __future__ import annotations

import argparse
from pathlib import Path

import duckdb

from cde.config import DB_PATH
from cde.explore import build_person_degree, explore
from cde.resolve import resolve_one_title

# Evaluation metadata only -- see module docstring. Never read by
# cde.explore; scoring/ranking has no idea this column exists.
EDGE_INTEGRITY_DEFAULT = "unverified"
EDGE_INTEGRITY_VALUES = (
    "valid", "wrong_role", "overbroad_role", "weak_credit", "version_problem",
    "unverified",
)

# 12 canonical seeds spanning eras (1920s-2000s) and countries/traditions,
# as (title, year) -- resolved against the real backbone, never hand-typed
# as tconsts.
SEEDS = [
    ("The Conformist", 1970),          # Italy, 1970s
    ("The Seventh Seal", 1957),        # Sweden, 1950s
    ("8 1/2", 1963),                   # Italy, 1960s
    ("The Shawshank Redemption", 1994),  # USA, 1990s
    ("Rashomon", 1950),                # Japan, 1950s
    ("Citizen Kane", 1941),            # USA, 1940s
    ("Breathless", 1960),              # France, 1960s (New Wave)
    ("Tokyo Story", 1953),             # Japan, 1950s
    ("Pather Panchali", 1955),         # India, 1950s
    ("The Godfather", 1972),           # USA, 1970s
    ("In the Mood for Love", 2000),    # Hong Kong, 2000s
    ("The Battleship Potemkin", 1925),  # USSR, 1920s (silent)
]


def _md_escape(s):
    return (s or "").replace("|", "\\|")


def run(n=10, out_path="eval/explore_eval.md", con=None, seeds=None, explore_kwargs=None):
    """con/seeds are injectable for testing (a tiny fixture db + a matching
    seed list) -- default to the real film.duckdb and the 12 canonical
    seeds. explore_kwargs is passed straight through to explore(), e.g. to
    turn a specific flag off for a targeted re-eval."""
    seeds = seeds if seeds is not None else SEEDS
    explore_kwargs = explore_kwargs or {}
    owns_con = con is None
    if owns_con:
        con = duckdb.connect(str(DB_PATH))

    try:
        person_degree = build_person_degree(con)

        rows = []  # (seed_label, rank, cand, tconst, score, explanation)
        unresolved = []

        for title, year in seeds:
            tconst = resolve_one_title(con, title, year)
            if tconst is None:
                unresolved.append((title, year))
                continue

            result = explore(con, tconst, n=n, person_degree=person_degree, **explore_kwargs)
            seed = result["seed"]
            seed_label = f"{seed['title']} ({seed['year']})"

            if not result["results"]:
                rows.append((seed_label, "-", "-", "-", "-", "(no connected films found)"))
                continue

            for rank, r in enumerate(result["results"], start=1):
                rows.append((
                    seed_label,
                    rank,
                    f"{r['title']} ({r['year']})",
                    r["tconst"],
                    r["score"],
                    r["explanation"],
                ))

        out_path = Path(out_path)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            f.write("# CineGraph Explore -- evaluation table\n\n")
            f.write(
                "Generated by `eval_explore.py`, after `PREDICTIONS.md` was written and "
                "committed. This harness produces the judgeable artifact only -- the "
                "`judgment` and `edge_integrity` columns are filled in by a separate "
                "human pass.\n\n"
            )
            if unresolved:
                f.write("**Unresolved seeds (dropped from this run):** ")
                f.write(", ".join(f"{t} ({y})" for t, y in unresolved))
                f.write("\n\n")

            f.write(
                "| seed | rank | result | tconst | score | explanation "
                "| judgment | edge_integrity |\n"
            )
            f.write("|---|---|---|---|---|---|---|---|\n")
            for row in rows:
                seed_label, rank, cand, tconst, score, expl = row
                edge_integrity = EDGE_INTEGRITY_DEFAULT if rank != "-" else ""
                f.write(
                    f"| {_md_escape(seed_label)} | {rank} | {_md_escape(str(cand))} | "
                    f"{tconst if tconst != '-' else '-'} | {score} | "
                    f"{_md_escape(str(expl))} | | {edge_integrity} |\n"
                )

        print(f"Wrote {out_path} ({len(rows)} rows, {len(seeds) - len(unresolved)}/{len(seeds)} "
              f"seeds resolved)")
        if unresolved:
            print("Unresolved:", unresolved)
        return out_path
    finally:
        if owns_con:
            con.close()


def main():
    parser = argparse.ArgumentParser(description="CineGraph Explore evaluation harness")
    parser.add_argument("--n", type=int, default=10, help="results per seed (default 10)")
    parser.add_argument("--out", default="eval/explore_eval.md", help="output markdown path")
    args = parser.parse_args()
    run(n=args.n, out_path=args.out)


if __name__ == "__main__":
    main()
